#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")"
clang -arch x86_64 -arch arm64 -mmacosx-version-min=11.0 -Os -Wall -Werror -Wno-deprecated-declarations \
    -fobjc-arc -fblocks -framework AppKit -framework Carbon hotkey.m -o cell-game-hotkey
codesign --force --sign - cell-game-hotkey >/dev/null 2>&1
python3 -I - <<'PY'
import base64
from pathlib import Path
data = Path('cell-game-hotkey').read_bytes()
encoded = base64.b64encode(data).decode()
lines = '\n'.join('        ' + encoded[i:i+100] for i in range(0, len(encoded), 100))
Path('../../Sources/CellCore/Launch/GameHotkeyBinary.swift').write_text(
    '// Generated by Tools/game-hotkey/build.sh. Do not edit.\nimport Foundation\n\nextension GameHotkey {\n'
    '    static let base64 = """\n' + lines + '\n        """\n}\n')
print('cell-game-hotkey:', len(data), 'bytes')
PY
