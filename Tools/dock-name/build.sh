#!/bin/bash
# Builds the Dock name library (x86_64 for Wine under Rosetta, arm64 for completeness) and embeds it in CellCore.
set -euo pipefail
cd "$(dirname "$0")"
OUT="${1:-libdockname.dylib}"
clang -arch x86_64 -arch arm64 -mmacosx-version-min=11.0 -Os -dynamiclib -Wall -Werror \
    -framework CoreFoundation -framework CoreGraphics -lobjc -fobjc-exceptions -Wl,-dead_strip -install_name @rpath/libdockname.dylib dockname.m -o "$OUT"
strip -x "$OUT"
codesign --force --sign - "$OUT" >/dev/null 2>&1
python3 -I - "$OUT" ../../Sources/CellCore/Launch/DockNameLibraryBinary.swift <<'PY'
import base64, hashlib, sys
data = open(sys.argv[1], "rb").read()
encoded = base64.b64encode(data).decode()
lines = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
text = ("// Generated by Tools/dock-name/build.sh from dockname.m. Do not edit.\nimport Foundation\n\n"
        "extension DockNames {\n"
        f"    static let sha256 = \"{hashlib.sha256(data).hexdigest()}\"\n"
        "    static let base64 = \"\"\"\n" + "\n".join(f"        {line}" for line in lines) + "\n        \"\"\"\n}\n")
open(sys.argv[2], "w").write(text)
print(f"{sys.argv[1]}: {len(data)} bytes")
PY
